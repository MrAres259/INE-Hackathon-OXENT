@functools.lru_cache(maxsize=1)
def get_catalog_keys() -> set[str]:
    """Retrieve set of known metric keys from seed/variables.csv and core catalog."""
    keys = set(CORE_CATALOG_KEYS)
    var_file = SEED_DIR / "variables.csv"
    if var_file.is_file():
        try:
            df = pd.read_csv(var_file, dtype=str)
            if "key" in df.columns:
                keys.update(df["key"].dropna().str.strip().tolist())
        except Exception:
            pass
    return keys


def is_valid_metric(m: str | None, valid_keys: set[str]) -> bool:
    """Check if metric key exists in catalog or matches wide column pattern."""
    if not m:
        return False
    if m in valid_keys:
        return True
    return bool(re.match(r"^(part|abst)_dip_\d{4}$", m))


class QuerySpec(BaseModel):
    """Specification of structured analytical query generated by planner."""

    intent: Literal[
        "ranking",
        "lookup",
        "compare",
        "correlation",
        "trend",
        "scenario",
        "explain_unit",
        "catalog",
        "help",
        "out_of_scope",
        "profile",
    ]
    level: Literal["state", "mun"] = "mun"
    metric: str = "risk_score"
    x_metric: str | None = None
    filters: dict[str, Any] = Field(default_factory=dict)
    year: int | None = None
    election: str = "DIP_FED"
    order: Literal["asc", "desc"] = "desc"
    limit: int = 10
    unit_ids: list[str] = Field(default_factory=list)
    scenario: str | None = None
    scenario_params: dict[str, Any] = Field(default_factory=dict)

    @model_validator(mode="after")
    def validate_spec(self) -> "QuerySpec":
        # 1. Clamp limit to 1..50
        if self.limit < 1:
            self.limit = 1
        elif self.limit > 50:
            self.limit = 50

        valid_keys = get_catalog_keys()

        # 2. Validate and adjust primary metric
        if not is_valid_metric(self.metric, valid_keys):
            matches = difflib.get_close_matches(self.metric, list(valid_keys), n=1, cutoff=0.55)
            if matches:
                self.metric = matches[0]
            else:
                self.intent = "catalog"

        # 3. Validate and adjust secondary x_metric (for correlation)
        if self.x_metric:
            if not is_valid_metric(self.x_metric, valid_keys):
                matches = difflib.get_close_matches(self.x_metric, list(valid_keys), n=1, cutoff=0.55)
                if matches:
                    self.x_metric = matches[0]
                else:
                    if self.intent == "correlation":
                        self.intent = "catalog"
                    self.x_metric = None

        return self


class DataResult(BaseModel):
    """Result data produced deterministically by the query executor."""

    columns: list[str] = Field(default_factory=list)
    rows: list[list[Any]] = Field(default_factory=list)
    source: str = ""
    facts: list[str] = Field(default_factory=list)
    empty: bool = False
